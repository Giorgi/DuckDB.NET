#!/usr/bin/env bash
# Regenerates the internal bindings of DuckDB's C API V2 (DuckDB.NET.Bindings/NativeMethods/V2/Generated) from the
# duckdb_v2.h that the build downloads with the native libraries, using ClangSharpPInvokeGenerator (pinned in
# dotnet-tools.json).
#
#   scripts/generate-v2-bindings.sh [path/to/duckdb_v2.h]
#
# Without an argument it takes the header from DuckDB.NET.Bindings/obj/runtimes, so build with /p:BuildType=Full
# first. ClangSharp needs the Clang resource directory for stdbool.h and friends: it is found with
# `clang -print-resource-dir`, or set CLANG_RESOURCE_DIR. On Windows, run it from Git Bash with LLVM installed.
#
# The bindings are internal: the V2 API is unstable, so they follow the header of the DuckDB build they were
# generated from and change with it. Commit the regenerated files together with the code that calls them.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

header="${1:-}"
if [ -z "$header" ]; then
  header=$(find DuckDB.NET.Bindings/obj/runtimes -name duckdb_v2.h 2>/dev/null | sort | head -n 1)
fi
if [ -z "$header" ] || [ ! -f "$header" ]; then
  echo "duckdb_v2.h not found. Build with /p:BuildType=Full first, or pass the header's path." >&2
  exit 1
fi

resource_dir="${CLANG_RESOURCE_DIR:-}"
if [ -z "$resource_dir" ] && command -v clang >/dev/null; then
  resource_dir=$(clang -print-resource-dir)
fi
if [ -z "$resource_dir" ] || [ ! -d "$resource_dir/include" ]; then
  echo "No Clang resource directory. Install clang, or set CLANG_RESOURCE_DIR to a directory that has include/stdbool.h." >&2
  exit 1
fi

out=DuckDB.NET.Bindings/NativeMethods/V2/Generated
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# The header is copied so that the generated NativeTypeName attributes and the traversal name one fixed file name.
cp "$header" "$work/duckdb_v2.h"
printf '%s\n' "// <auto-generated>" \
  "// Generated by scripts/generate-v2-bindings.sh from duckdb_v2.h. Do not edit: regenerate instead." \
  "// </auto-generated>" > "$work/file-header.txt"

dotnet tool restore >/dev/null

# Run from the repository root, where dotnet finds the tool manifest.
dotnet tool run ClangSharpPInvokeGenerator \
  --file "$work/duckdb_v2.h" \
  --traverse "$work/duckdb_v2.h" \
  --define-macro DUCKDB_V2_API_ALLOW_UNSTABLE=1 \
  --namespace DuckDB.NET.Native.V2 \
  --method-class-name NativeMethodsV2 \
  --library-path duckdb \
  --output "$work/generated" \
  --header-file "$work/file-header.txt" \
  --resource-directory "$resource_dir" \
  --with-access-specifier '*=Internal' \
  --config file=multi \
  --config types=unix \
  --generate file-scoped-namespaces \
  --generate helper-types \
  --generate generated-code=type \
  --generate enum-member-type-name=false \
  > "$work/generator.log" 2>&1 || true

# The exit code is not a verdict: the tool also exits non-zero for warnings. The only diagnostics expected are the
# 'Visibility' attribute of DUCKDB_C_API, which P/Invoke has no use for; anything else fails the generation.
if grep -E '^\s*(Error|Warning|Fatal)|error:' "$work/generator.log" | grep -v "Unsupported attribute: 'Visibility'" >&2; then
  echo "ClangSharpPInvokeGenerator reported the diagnostics above." >&2
  exit 1
fi
if [ ! -f "$work/generated/NativeMethodsV2.cs" ]; then
  cat "$work/generator.log" >&2
  echo "ClangSharpPInvokeGenerator generated no bindings." >&2
  exit 1
fi

rm -rf "$out"
mkdir -p "$out"
cp -r "$work/generated/." "$out/"
echo "Generated $(find "$out" -name '*.cs' | wc -l | tr -d ' ') files into $out from $header"
